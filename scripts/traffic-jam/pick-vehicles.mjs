#!/usr/bin/env node
/**
 * Copies the vehicle sprites Traffic Jam uses out of the "TopDown Vehicles"
 * pack by @MinZiin_ (https://minzinn.itch.io/, CC BY 4.0), trimmed to their
 * visible pixels and converted to lossless WebP, and writes
 * src/programs/traffic-jam/data/vehicles.ts. Needs ImageMagick (`magick`).
 *
 *   node scripts/traffic-jam/pick-vehicles.mjs ["path/to/TopDown Vehicles v1.17"]
 *
 * The pack itself isn't in the repo (it's ~27k files); only the picked
 * frames are.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const pack = process.argv[2] ?? join(root, "TopDown Vehicles v1.17");
const program = join(root, "src/programs/traffic-jam");
const assets = join(program, "assets/vehicles");

/** [pack folder, colour folder or null when the model has one colour]. */
const HERO = ["SPORT TOPDOWN", "Red"];
const CARS = [
  ["SEDAN TOPDOWN", "Blue"],
  ["TAXI TOPDOWN", null],
  ["POLICE TOPDOWN", null],
  ["PICKUP TOPDOWN", "Green"],
  ["COUPE TOPDOWN", "Yellow"],
  ["HATCHBACK TOPDOWN", "Magenta"],
  ["SUV TOPDOWN", "White"],
  ["MINIVAN TOPDOWN", "Brown"],
  ["WAGON TOPDOWN", "Black"],
  ["MUSCLECAR TOPDOWN", "Green"],
  ["LUXURY TOPDOWN", "White"],
  ["VAN TOP DOWN", "Blue"],
];
const TRUCKS = [
  ["BUS TOPDOWN", "Yellow"],
  ["LIMO TOPDOWN", "Black"],
  ["BOX TRUCK TOPDOWN", "White"],
  ["MEDIUM TRUCK TOPDOWN", "Blue"],
  ["CAMPER TOPDOWN", "White"],
  ["AMBULANCE TOPDOWN", null],
];
const DIRECTIONS = ["east", "west", "north", "south"];

const slug = ([folder, colour]) =>
  [folder.replace(/TOP ?DOWN/, "").trim(), colour].filter(Boolean).join(" ").toLowerCase().replace(/\s+/g, "-");
const camel = (text) => text.replace(/-(\w)/g, (_, c) => c.toUpperCase());

rmSync(assets, { recursive: true, force: true });
mkdirSync(assets, { recursive: true });

const imports = [];
function copy(vehicle) {
  const name = slug(vehicle);
  const [folder, colour] = vehicle;
  const sprite = {};
  for (const direction of DIRECTIONS) {
    const dir = join(pack, folder, colour ?? "", "MOVE", direction.toUpperCase(), "SEPARATED");
    const frame = readdirSync(dir).filter((f) => f.endsWith("_000.png")).sort()[0];
    if (!frame) throw new Error(`No first frame in ${dir}`);
    const file = `${name}-${direction}.webp`;
    execFileSync("magick", [join(dir, frame), "-trim", "+repage", "-define", "webp:lossless=true", join(assets, file)]);
    const id = camel(`${name}-${direction}`);
    imports.push(`import ${id} from "../assets/vehicles/${file}";`);
    sprite[direction] = id;
  }
  return `{ name: "${name}", ${DIRECTIONS.map((d) => `${d}: ${sprite[d]}`).join(", ")} }`;
}

const hero = copy(HERO);
const cars = CARS.map(copy);
const trucks = TRUCKS.map(copy);

writeFileSync(
  join(program, "data/vehicles.ts"),
  `/**
 * Generated by scripts/traffic-jam/pick-vehicles.mjs, don't edit by hand.
 *
 * Sprites from "TopDown Vehicles" by @MinZiin_ (https://minzinn.itch.io/),
 * licensed CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).
 * Changes: first frame of each direction only, trimmed, converted to WebP.
 */
import type { StaticImageData } from "next/image";

${imports.join("\n")}

export type VehicleSprite = {
  name: string;
  east: StaticImageData;
  west: StaticImageData;
  north: StaticImageData;
  south: StaticImageData;
};

/** The red car you have to get out. */
export const HERO: VehicleSprite = ${hero};

/** Two cells long. */
export const CARS: readonly VehicleSprite[] = [
${cars.map((c) => `  ${c},`).join("\n")}
];

/** Three cells long. */
export const TRUCKS: readonly VehicleSprite[] = [
${trucks.map((t) => `  ${t},`).join("\n")}
];
`,
);
console.log(`Wrote ${imports.length} sprites to ${assets}`);
