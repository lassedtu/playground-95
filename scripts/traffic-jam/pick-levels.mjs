#!/usr/bin/env node
/**
 * Picks Traffic Jam's levels and daily puzzles from Michael Fogleman's
 * Rush Hour database (https://www.michaelfogleman.com/rush/) and writes
 * src/programs/traffic-jam/data/levels.ts.
 *
 *   node scripts/traffic-jam/pick-levels.mjs [path/to/rush.txt.gz]
 *
 * Without a path the database (~33 MB) is downloaded to the temp folder.
 * Puzzles with walls are skipped (they aren't in the original game). Every
 * pick is re-solved with the game's own solver to check its par. The choice
 * is seeded, so running it again gives the same file.
 */
import { createReadStream, existsSync, writeFileSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createInterface } from "node:readline";
import { createGunzip } from "node:zlib";

const DATABASE_URL = "https://www.michaelfogleman.com/static/rush/rush.txt.gz";
const root = new URL("../../", import.meta.url);
const OUTPUT = new URL("src/programs/traffic-jam/data/levels.ts", root);
const { parseBoard, solve } = await import(new URL("src/programs/traffic-jam/lib/board.ts", root).href);

/** 50 levels per tier, spread evenly over these optimal move counts. */
const TIERS = [
  { name: "Beginner", from: 4, to: 12 },
  { name: "Intermediate", from: 13, to: 21 },
  { name: "Advanced", from: 22, to: 31 },
  { name: "Expert", from: 32, to: 51 },
];
const PER_TIER = 50;
/** One daily puzzle per day for a year before it repeats, medium difficulty. */
const DAILY_COUNT = 365;
const DAILY_MOVES = { from: 14, to: 30 };

let seed = 95;
const random = () => {
  seed = (seed * 1_103_515_245 + 12_345) % 2_147_483_648;
  return seed / 2_147_483_648;
};

async function databasePath() {
  if (process.argv[2]) return process.argv[2];
  const path = join(tmpdir(), "rush.txt.gz");
  if (!existsSync(path)) {
    console.log(`Downloading ${DATABASE_URL}…`);
    const response = await fetch(DATABASE_URL);
    if (!response.ok) throw new Error(`Download failed: ${response.status}`);
    await writeFile(path, Buffer.from(await response.arrayBuffer()));
  }
  return path;
}

// Wall-free puzzles grouped by optimal move count.
const byMoves = new Map();
const lines = createInterface({ input: createReadStream(await databasePath()).pipe(createGunzip()) });
for await (const line of lines) {
  const [moves, board] = line.split(" ");
  if (!board || board.includes("x")) continue;
  const par = Number(moves);
  if (!byMoves.has(par)) byMoves.set(par, []);
  byMoves.get(par).push(board);
}

const used = new Set();
/** A random unused puzzle with exactly `par` moves, or the closest count that has one. */
function pick(par) {
  for (let distance = 0; distance < 60; distance++) {
    for (const candidate of [par + distance, par - distance]) {
      const boards = (byMoves.get(candidate) ?? []).filter((b) => !used.has(b));
      if (!boards.length) continue;
      const board = boards[Math.floor(random() * boards.length)];
      used.add(board);
      return [candidate, board];
    }
  }
  throw new Error(`No puzzle near ${par} moves`);
}

const levels = TIERS.flatMap(({ from, to }) =>
  Array.from({ length: PER_TIER }, (_, i) => pick(Math.round(from + ((to - from) * i) / (PER_TIER - 1)))),
);
// Sorted within each tier so levels get gradually harder.
for (let t = 0; t < TIERS.length; t++) {
  const tier = levels.slice(t * PER_TIER, (t + 1) * PER_TIER).sort((a, b) => a[0] - b[0]);
  levels.splice(t * PER_TIER, PER_TIER, ...tier);
}
const daily = Array.from({ length: DAILY_COUNT }, () =>
  pick(DAILY_MOVES.from + Math.floor(random() * (DAILY_MOVES.to - DAILY_MOVES.from + 1))),
);

for (const [par, board] of [...levels, ...daily]) {
  const solution = solve(parseBoard(board));
  if (solution?.length !== par) throw new Error(`${board}: database says ${par}, solver says ${solution?.length}`);
}

const list = (puzzles) => puzzles.map(([par, board]) => `  [${par}, "${board}"],`).join("\n");
writeFileSync(
  OUTPUT,
  `/**
 * Generated by scripts/traffic-jam/pick-levels.mjs, don't edit by hand.
 *
 * Puzzles from Michael Fogleman's Rush Hour database
 * (https://www.michaelfogleman.com/rush/). Each entry is [par, board]: the
 * fewest moves that solve it and the 36-character board in row-major order
 * ("o" = empty, "A" = red car, other letters = vehicles).
 */
export type Puzzle = readonly [par: number, board: string];

/** ${TIERS.length * PER_TIER} levels: ${TIERS.map((t) => t.name).join(", ")}, ${PER_TIER} each, easiest first. */
export const LEVELS: readonly Puzzle[] = [
${list(levels)}
];

export const TIER_NAMES = ${JSON.stringify(TIERS.map((t) => t.name))} as const;
export const LEVELS_PER_TIER = ${PER_TIER};

/** Daily puzzles (${DAILY_MOVES.from}–${DAILY_MOVES.to} moves), none of them also a level. */
export const DAILY: readonly Puzzle[] = [
${list(daily)}
];
`,
);
console.log(`Wrote ${levels.length} levels and ${daily.length} daily puzzles to ${OUTPUT.pathname}`);
